// Trains a brain offline with exactly the code the browser runs (main.js with
// auto-train on), starting from random brains, and writes it to pretrained.js.
//
// Usage: node tools/train.js [generations=40] [seed=1] [fixed|random] [output=pretrained.js]
//   fixed  - every generation drives the same traffic layout (fast, but the brain can memorise it)
//   random - every generation gets a new random layout, so memorising one road stops paying off
const fs=require("fs");
const path=require("path");
const vm=require("vm");
const {ROOT,pageScripts,installBrowserStubs,loadScripts,seedMathRandom,pageGlobal}=require("./headless");

const generations=Number(process.argv[2])||40;
const seed=Number(process.argv[3])||1;
const trafficMode=process.argv[4]=="random"?"random":"fixed";
const output=path.resolve(ROOT,process.argv[5]||"pretrained.js");

seedMathRandom(seed);
const storage=installBrowserStubs({bestBrain:""});   // "" = start from random brains
globalThis.location={search:trafficMode=="random"?"?traffic=random":""};
loadScripts(pageScripts());
vm.runInThisContext("autoTrain=true;");

let reported=0;
while(pageGlobal("generation")<=generations){
    pageGlobal("simulationStep")();
    const history=pageGlobal("history");
    while(reported<history.length){
        const g=history[reported++];
        console.log("generation "+String(g.generation).padStart(3)+
            ": best car overtook "+g.passed+"/"+g.total+(g.crashed?" (then crashed)":""));
    }
}

if(!storage.bestBrain){
    console.log("No car overtook anything - pretrained.js was not changed. Try another seed.");
    process.exit(1);
}
const header="// Generated by tools/train.js ("+generations+" generations, seed "+seed+", "+
    trafficMode+" traffic) - do not edit by hand.\n";
fs.writeFileSync(output,header+"const PRETRAINED_BRAIN="+storage.bestBrain+";\n");
console.log("Saved the best brain to "+path.relative(ROOT,output));
